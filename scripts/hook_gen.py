#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""生成 Frida Java hook 脚本；可选一键注入真机并打印命中日志。

默认只生成（行为和以前一样，打印到 stdout 或 --out 写文件）：

    python3 hook_gen.py --class com.example.Foo --method check
    python3 hook_gen.py --class com.example.Foo --method check --args --return true
    python3 hook_gen.py --class com.example.Foo --method check \
        --overload 'java.lang.String,int' --return int --out /tmp/hook.js

一键注入（生成后自动 attach 目标、加载 hook、打印命中）：

    python3 hook_gen.py --class android.app.Activity --method onCreate \
        --run --package com.example.app
    python3 hook_gen.py --class com.example.Foo --method check \
        --run --pid 1234 --duration 20
    # App 启动即检测/要 hook 启动阶段？先 spawn 再注入：
    python3 hook_gen.py --class com.example.Foo --method check \
        --run --spawn --package com.example.app --duration 15

注入模式说明:
  - 目标用 --package <包名> 或 --pid <PID> 指定（二选一）；
  - --run 默认 attach 已运行的进程；加 --spawn 由本工具先启动 App 再注入（退出时会结束它）；
  - --host 默认 127.0.0.1:27043（设备上的 frida-server，root 启动）；
  - --duration 默认 10 秒；--duration 0 表示一直等到 Ctrl-C；
  - 到时或 Ctrl-C 会 detach 并退出，不留后台脚本；退出码 0=已安装，1=未确认安装，
    2=连接/attach/Java/类方法等错误；
  - Frida 17 的 Python API 默认不带 Java bridge，本工具会从 frida-tools 自动注入
    globalThis.Java（需要 pip install frida-tools）。

生成参数:
  --return original|true|false|int:<n>|string:<s>|null
  --args        打印每个入参
  --overload    重载签名，逗号分隔；省略则 hook 该方法的全部重载（逐个安装）
  --out         写文件；只生成模式省略则打印到 stdout，--run 模式建议加 --out 存档

前置:
  - 手机已装 frida-server 并已启动（bash scripts/frida_server_prep.sh --status 可查）；
  - 本机 pip 的 frida 版本与设备 frida-server 一致（本技能：17.26.2）。
"""
import argparse
import json
import re
import sys
import time

JAVA_ID = re.compile(r'^[A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*$')
METHOD_ID = re.compile(r'^[A-Za-z_$<>][\w$<>]*$')

# Frida 17 的 Python API 不自动带 Java bridge（只有 frida CLI 带）。
# 从 frida-tools 取 bridge 源码，挂到 globalThis.Java，否则脚本里 typeof Java === 'undefined'。
JAVA_BRIDGE_SHIM = ('Object.defineProperty(globalThis, "Java", '
                    '{value: bridge, configurable: true});\n')


def js_literal(kind, value):
    if kind == 'true':
        return 'true'
    if kind == 'false':
        return 'false'
    if kind == 'null':
        return 'null'
    if kind == 'int':
        try:
            return str(int(value))
        except ValueError:
            raise ValueError('int 返回值必须是整数')
    if kind == 'string':
        # 用 JSON 编码：换行 / 引号 / 反斜杠 / 制表符 / 控制字符都会被转义，
        # 避免字符串里带换行时生成非法 JS（旧版只转义 \ 和 "）。
        lit = json.dumps(value, ensure_ascii=False)
        # U+2028/U+2029 在 JSON 里合法，但老引擎的 JS 字符串里会被当换行符
        return lit.replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    if kind == 'original':
        return '__orig'
    raise ValueError('未知返回类型: %s' % kind)


def build(args):
    """生成 Frida Java hook JS（不依赖 frida，纯文本）。"""
    cls = args.klass.strip()
    method = args.method.strip()
    if not JAVA_ID.match(cls):
        raise ValueError('类名不合法: %s' % cls)
    if not METHOD_ID.match(method):
        raise ValueError('方法名不合法: %s' % method)

    overload = None
    if args.overload:
        parts = [p.strip() for p in args.overload.split(',') if p.strip()]
        overload = ', '.join("'%s'" % p.replace("'", '') for p in parts)

    ret_kind, ret_val = 'original', ''
    if args.return_value != 'original':
        kind, _, val = args.return_value.partition(':')
        ret_kind, ret_val = kind, val
    ret_js = js_literal(ret_kind, ret_val) if ret_kind != 'original' else '__orig'

    if ret_kind == 'original':
        return_expr = 'ret'
    elif ret_kind == 'null':
        return_expr = 'null'
    elif ret_kind == 'string':
        return_expr = ret_js
    else:
        return_expr = ret_js

    arg_log = ''
    if args.args:
        arg_log = ('      for (var i = 0; i < arguments.length; i++) {\n'
                   '        console.log("  arg[" + i + "] = " + __hook_fmt(arguments[i]));\n'
                   '      }\n')

    # Frida 17：在“有多个重载”的方法上直接 .implementation = ... 会报
    # “has more than one overload”，所以未指定 --overload 时逐个重载安装（等价于全匹配）。
    if overload:
        targets_expr = '[Cls["%s"].overload(%s)]' % (method, overload)
    else:
        targets_expr = 'Cls["%s"].overloads' % method
    js = '''// generated by hook_gen.py
// 目标: %s.%s
// 用法: 可直接给 frida CLI（frida -H 127.0.0.1:27043 -f <包名> -l 本文件）加载；
//       或回到 hook_gen.py 加 --run 一键注入。
function __hook_fmt(v) {
  try { return String(v); } catch (e) { return "<无法显示>"; }
}
Java.perform(function () {
  var Cls = Java.use("%s");
  if (Cls["%s"] === undefined) {
    throw new Error("找不到方法: %s.%s（类已加载，但类里没有这个方法；检查 --method 拼写）");
  }
  var targets = %s;
  for (var __i = 0; __i < targets.length; __i++) {
    targets[__i].implementation = function () {
      console.log("[hook] %s.%s called");
%s      var ret = this["%s"].apply(this, arguments);
      console.log("[hook] ret = " + __hook_fmt(ret));
      send({type: "hook_hit", target: "%s.%s", ret: __hook_fmt(ret)});
      return %s;
    };
  }
  console.log("[hook] installed: %s.%s（%s）");
  send({type: "hook_ready", target: "%s.%s"});
});
''' % (cls, method, cls, method, cls, method, targets_expr,
       cls, method, arg_log, method, cls, method, return_expr,
       cls, method, ('已指定重载' if overload else '全部重载'), cls, method)
    return js


# ── 注入模式 ────────────────────────────────────────────────────────────────

def _print_err(msg):
    print('错误: %s' % msg, file=sys.stderr)


def _load_java_bridge():
    """返回可拼到脚本前面的 Java bridge 源码；失败抛异常。"""
    import pathlib
    import frida_tools
    bridge_path = pathlib.Path(frida_tools.__file__).parent / 'bridges' / 'java.js'
    return bridge_path.read_text(encoding='utf-8') + '\n' + JAVA_BRIDGE_SHIM


def _explain_script_error(desc, stack):
    """把 Frida 脚本错误翻译成新手能看懂的中文提示。"""
    low = (desc + '\n' + stack).lower()
    if ('java is not defined' in low or 'java api is not available' in low
            or 'java api not available' in low or 'java vm not available' in low
            or 'cannot find java' in low or 'java bridge' in low):
        return ('Java VM 不可用：目标进程不是 Android/Java 进程，或 Java bridge 没加载成功。\n'
                '→ 确认目标是 Android App；确认本机 pip install frida-tools（bridge 来自它）。')
    if 'classnotfound' in low or "couldn't find class" in low or 'class not found' in low \
            or 'classloader' in low:
        return ('找不到类：确认 --class 是反编译里的完整类名（带包名）。\n'
                '→ 有些类要等 App 启动后才加载，可加 --spawn 从启动开始 hook。')
    if ('找不到方法' in low or 'cannot find method' in low or 'method not found' in low
            or 'no method' in low or 'overload' in low or 'argument types' in low):
        return ('找不到方法/重载：确认 --method 拼写；有重载时用 --overload 指定参数类型，\n'
                '   如 --overload java.lang.String,int（用 jadx 或 javap 看签名）。')
    if 'permission' in low or 'denied' in low:
        return ('注入被拒绝：目标进程可能反调试，或 frida-server 权限/版本不对。\n'
                '→ 试 --spawn；确认设备上 frida-server 是 root 启动且版本与本机 frida 一致。')
    return 'Frida 脚本报错: %s（详细堆栈见下方原始信息）' % desc.strip()


def _find_pid_by_package(dev, package):
    """包名 → 进程 PID。Android 进程名常是显示名（如“全球网测”），必须查应用表。"""
    try:
        for app in dev.enumerate_applications():
            if app.identifier == package and app.pid:
                return app.pid
    except Exception:
        pass
    try:
        for proc in dev.enumerate_processes():
            ident = getattr(proc, 'identifier', None)
            if proc.name == package or ident == package:
                return proc.pid
    except Exception:
        pass
    return None


def _attach(dev, args):
    """按 --pid / --package attach；失败时抛带新手提示的 RuntimeError。"""
    import frida
    try:
        if args.pid:
            return dev.attach(args.pid)
        try:
            return dev.attach(args.package)
        except frida.ProcessNotFoundError:
            # attach 包名时 frida 按进程名找；Android 的进程名可能是 App 显示名而非包名
            pid = _find_pid_by_package(dev, args.package)
            if pid is None:
                raise
            return dev.attach(pid)
    except frida.ProcessNotFoundError:
        raise RuntimeError(
            '目标进程不存在: %s\n'
            '→ App 可能没启动/已被系统回收：先手动打开它，或加 --spawn 让本工具来启动。'
            % (args.package or args.pid))
    except frida.ServerNotRunningError:
        raise RuntimeError(
            'frida-server 没在运行（%s）。\n'
            '→ 先启动：bash scripts/frida_server_prep.sh --auto（或 --status 检查）' % args.host)
    except frida.TransportError as exc:
        raise RuntimeError(
            '连接 frida-server 失败（%s）: %s\n'
            '→ 检查 frida-server 是否已启动、端口是否 27043、本机 frida 版本是否与设备一致。'
            % (args.host, exc))
    except frida.TimedOutError as exc:
        raise RuntimeError(
            'attach 超时（%s）: %s\n'
            '→ App 可能卡死/反调试；可重启 App、改 --spawn，或确认 frida-server 正常。'
            % (args.host, exc))
    except Exception as exc:
        raise RuntimeError('无法 attach %s: %s: %s'
                           % (args.package or args.pid, type(exc).__name__, exc))


def _start_session(dev, args):
    """spawn 或 attach，返回 (session, spawned_pid)；失败抛 RuntimeError。

    中断（Ctrl-C）也统一清理已 spawn 的进程，避免留下冻结的后台进程。
    """
    import frida
    spawned_pid = None
    try:
        if args.package and args.spawn:
            try:
                spawned_pid = dev.spawn(args.package)
            except frida.ProcessNotFoundError:
                raise RuntimeError(
                    '找不到包: %s（确认已安装：adb shell pm list packages | grep 包名）'
                    % args.package)
            except Exception as exc:
                if 'unable to find application' in str(exc).lower():
                    raise RuntimeError(
                        '找不到包: %s（没安装或包名写错；adb shell pm list packages | grep 包名）'
                        % args.package)
                raise RuntimeError('spawn %s 失败: %s: %s'
                                   % (args.package, type(exc).__name__, exc))
            try:
                session = dev.attach(spawned_pid)
            except Exception as exc:
                raise RuntimeError('spawn 后 attach 失败: %s: %s'
                                   % (type(exc).__name__, exc))
            print('[*] 已 spawn: %s (pid %s)，hook 安装后 resume'
                  % (args.package, spawned_pid), flush=True)
            return session, spawned_pid
        session = _attach(dev, args)
        print('[*] 已 attach: %s' % (args.package or ('pid %s' % args.pid)),
              flush=True)
        return session, None
    except BaseException:
        if spawned_pid is not None:
            try:
                dev.kill(spawned_pid)
            except Exception:
                pass
        raise


def run_inject(js, args):
    """生成后一键注入：attach/spawn → 加载 hook+bridge → 打印命中 → detach。"""
    try:
        import frida
    except ImportError:
        _print_err('注入模式需要 frida-python：pip install frida frida-tools（版本与设备 frida-server 一致）')
        return 2

    target_name = '%s.%s' % (args.klass, args.method)
    print('[*] 生成 hook: %s' % target_name)
    print('[*] 连接 frida-server: %s' % args.host)
    try:
        dev = frida.get_device_manager().add_remote_device(args.host)
    except Exception as exc:
        _print_err('无法连接 frida-server %s: %s\n'
                   '→ 先启动 frida-server（bash scripts/frida_server_prep.sh --auto），'
                   '再确认本机 frida 版本与设备一致。' % (args.host, exc))
        return 2

    spawned_pid = None
    try:
        session, spawned_pid = _start_session(dev, args)
    except RuntimeError as exc:
        _print_err(str(exc))
        return 2

    try:
        try:
            bridge = _load_java_bridge()
            print('[*] Java bridge 已注入（Frida 17 Python API 默认不带）', flush=True)
        except Exception as exc:
            _print_err('无法加载 Java bridge: %s\n'
                       '→ pip install frida-tools（hook 需要 globalThis.Java）' % exc)
            return 2

        state = {'ready': False, 'hits': 0, 'fatal': None}

        def on_message(message, data):
            mtype = message.get('type')
            if mtype == 'log':
                print('    ' + str(message.get('payload', '')))
                sys.stdout.flush()
                return
            if mtype == 'send':
                payload = message.get('payload') or {}
                ptype = payload.get('type')
                if ptype == 'hook_ready':
                    state['ready'] = True
                    print('[+] hook 已安装: %s' % payload.get('target', target_name))
                    sys.stdout.flush()
                elif ptype == 'hook_hit':
                    state['hits'] += 1
                    ret = payload.get('ret')
                    line = '[命中] %s' % payload.get('target', target_name)
                    if ret is not None:
                        line += '  返回: %s' % ret
                    print(line)
                    sys.stdout.flush()
                return
            if mtype == 'error':
                desc = message.get('description') or '脚本错误'
                stack = message.get('stack') or ''
                state['fatal'] = _explain_script_error(desc, stack)
                print('[错误] ' + state['fatal'], file=sys.stderr)
                # 保留原始报错，方便 AI/老手进一步查（新手可只看上面的人话提示）
                print('  ── 原始信息 ──', file=sys.stderr)
                print('  ' + desc.strip(), file=sys.stderr)
                if stack.strip():
                    print('  ' + stack.strip().replace('\n', '\n  '), file=sys.stderr)
                sys.stderr.flush()

        try:
            script = session.create_script(bridge + js)
            script.on('message', on_message)
            script.load()
        except Exception as exc:
            _print_err('加载 hook 脚本失败: %s: %s\n'
                       '→ 常见原因：类/方法写错、App 反调试、frida-server 版本不匹配。'
                       % (type(exc).__name__, exc))
            return 2

        if spawned_pid is not None:
            try:
                dev.resume(spawned_pid)
                print('[*] 已 resume App')
            except Exception as exc:
                _print_err('resume 失败: %s: %s' % (type(exc).__name__, exc))
                return 2

        try:
            # 给脚本一点时间报告“已安装”或报错，避免错误信息排在“开始观察”后面
            settle_deadline = time.time() + 2.0
            while (not state['ready'] and not state['fatal']
                   and time.time() < settle_deadline):
                time.sleep(0.05)
            if state['fatal']:
                return _finish(dev, session, state, args, spawned_pid)
            print('[*] 开始观察 %s'
                  % ('直到 Ctrl-C' if args.duration == 0 else '%ss' % args.duration),
                  flush=True)

            deadline = None if args.duration == 0 else time.time() + args.duration
            while True:
                if state['fatal']:
                    break
                if deadline is not None and time.time() >= deadline:
                    break
                time.sleep(0.2)
        except KeyboardInterrupt:
            print('\n[*] 收到 Ctrl-C，准备退出')

        return _finish(dev, session, state, args, spawned_pid)
    finally:
        # 兜底：任何异常路径都尽量 detach + 结束 spawn 的进程，不留后台残留
        try:
            session.detach()
        except Exception:
            pass
        if spawned_pid is not None and getattr(args, '_spawn_alive', True):
            args._spawn_alive = False
            try:
                dev.kill(spawned_pid)
                print('[*] 已结束 spawn 的进程 (pid %s)' % spawned_pid)
            except Exception:
                pass


def _finish(dev, session, state, args, spawned_pid):
    hits = state['hits']
    try:
        session.detach()
    except Exception:
        pass
    args._spawn_alive = False
    tail = '已 detach，无后台残留'
    if spawned_pid is not None:
        try:
            dev.kill(spawned_pid)
            tail = '已 detach，并结束 spawn 的进程 (pid %s)' % spawned_pid
        except Exception:
            tail = '已 detach，spawn 的进程也已退出（无后台残留）'
    if state['fatal']:
        print('[完成] 出错退出；命中 %d 次；%s' % (hits, tail), file=sys.stderr)
        return 2
    if not state['ready']:
        print('[完成] 命中 %d 次；%s' % (hits, tail))
        print('[警告] 没等到 “hook 已安装” 确认：目标进程的 Java VM 可能未就绪，'
              '或类还没加载。可加 --spawn / 延长 --duration 再试。', file=sys.stderr)
        return 1
    print('[完成] 命中 %d 次；%s' % (hits, tail))
    if hits == 0:
        if args.duration == 0:
            print('[提示] hook 已安装，但观察期内没有命中；操作 App 触发该方试试。')
        else:
            print('[提示] hook 已安装，但 %ss 内没有命中：目标方法可能没被调用，'
                  '试着操作 App 触发它，或加 --spawn 从启动开始 hook。' % args.duration)
    return 0


# ── CLI ─────────────────────────────────────────────────────────────────────

def main(argv=None):
    ap = argparse.ArgumentParser(
        prog='hook_gen.py',
        description='生成 Frida Java hook 脚本；加 --run 可一键注入并打印命中日志。',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog='''示例:
  只生成（默认，行为不变）:
    python3 hook_gen.py --class com.example.Foo --method check --out /tmp/hook.js
  一键注入（先手动打开 App）:
    python3 hook_gen.py --class android.app.Activity --method onCreate --run --package com.example.app
  从启动开始 hook（App 启动即检测时用）:
    python3 hook_gen.py --class com.example.Foo --method check --run --spawn --package com.example.app
  按 PID 注入并观察 30 秒:
    python3 hook_gen.py --class com.example.Foo --method check --run --pid 1234 --duration 30
''')
    ap.add_argument('--class', dest='klass', required=True, help='Java 类名，如 com.foo.Bar')
    ap.add_argument('--method', required=True, help='方法名')
    ap.add_argument('--overload', help='重载签名，逗号分隔，如 java.lang.String,int')
    ap.add_argument('--return', dest='return_value', default='original',
                    help='original|true|false|null|int:<n>|string:<s>（默认 original）')
    ap.add_argument('--args', action='store_true', help='打印每个入参')
    ap.add_argument('--out', help='写入文件；只生成模式省略则打印到 stdout，--run 模式建议加 --out 存档')

    g = ap.add_mutually_exclusive_group()
    g.add_argument('--package', help='一键注入目标包名（配合 --run；可加 --spawn）')
    g.add_argument('--pid', type=int, help='一键注入目标 PID（配合 --run）')
    ap.add_argument('--run', '--inject', dest='run', action='store_true',
                    help='生成后自动注入并打印命中/返回值（需要 --package 或 --pid）')
    ap.add_argument('--spawn', action='store_true',
                    help='先启动 App 再注入（需配合 --run --package；退出时结束该进程）')
    ap.add_argument('--host', default='127.0.0.1:27043',
                    help='frida-server 地址（默认 127.0.0.1:27043）')
    ap.add_argument('--duration', type=int, default=10,
                    help='观察秒数（默认 10；0 = 一直等到 Ctrl-C）')
    args = ap.parse_args(argv)

    if not args.run:
        if args.package or args.pid or args.spawn:
            _print_err('指定了 --package/--pid/--spawn，但没有 --run（只生成模式不需要目标）。\n'
                       '→ 想一键注入就加 --run，例如：\n'
                       '   python3 hook_gen.py --class %s --method %s --run --package <包名>'
                       % (args.klass, args.method))
            return 2
    else:
        if not (args.package or args.pid):
            _print_err('--run 需要指定目标：--package <包名> 或 --pid <PID>。\n'
                       '→ 例：python3 hook_gen.py --class %s --method %s --run --package com.example.app'
                       % (args.klass, args.method))
            return 2
        if args.spawn and not args.package:
            _print_err('--spawn 只能配合 --package 使用（spawn 要包名，不能按 PID 启动）')
            return 2
        if args.duration < 0:
            _print_err('--duration 不能是负数（0 表示一直等到 Ctrl-C）')
            return 2

    try:
        js = build(args)
    except ValueError as exc:
        _print_err(str(exc))
        return 2

    if args.out:
        with open(args.out, 'w', encoding='utf-8') as f:
            f.write(js)
        print('已写入: %s' % args.out)
    elif not args.run:
        print(js)

    if args.run:
        args._spawn_alive = True
        try:
            return run_inject(js, args)
        except KeyboardInterrupt:
            # 安装/attach 阶段被 Ctrl-C：run_inject 的 finally 已负责 detach
            print('\n[*] 已中断（注入未开始或已清理）', file=sys.stderr)
            return 130
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
